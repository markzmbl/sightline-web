// Generates src/api/schema.d.ts from the API contract. Sources, first found wins:
//   1. SIGHTLINE_OPENAPI (a path or an http(s) URL)
//   2. ../sightline-backend/contract/openapi.json (the backend's published contract)
//   3. contract/openapi.draft.yaml (the provisional draft kept here until then)
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const candidates = [
  process.env.SIGHTLINE_OPENAPI,
  resolve(root, "../sightline-backend/contract/openapi.json"),
  resolve(root, "contract/openapi.draft.yaml"),
].filter(Boolean);

const source = candidates.find((c) => /^https?:/.test(c) || existsSync(c));
if (!source) throw new Error(`no contract found; looked at ${candidates.join(", ")}`);

const url = /^https?:/.test(source) ? new URL(source) : pathToFileURL(source);
const ast = await openapiTS(url, { alphabetize: false, defaultNonNullable: true });
const banner = `// Generated by scripts/gen-api.mjs from ${/^https?:/.test(source) ? source : source.replace(root, ".")}.\n// Do not edit; run \`npm run gen:api\` instead.\n\n`;
writeFileSync(resolve(root, "src/api/schema.d.ts"), banner + astToString(ast));
console.log(`src/api/schema.d.ts written from ${source}`);
